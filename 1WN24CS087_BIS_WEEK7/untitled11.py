import random
from concurrent.futures import ProcessPoolExecutor

# 1. Take Inputs from the User
print("--- Wildfire Containment Cellular Algorithm ---")
GRID_SIZE = int(input("Enter terrain grid size (e.g., 10 for 10x10): "))
IGNITE_X = int(input(f"Enter fire start X coordinate (0 to {GRID_SIZE-1}): "))
IGNITE_Y = int(input(f"Enter fire start Y coordinate (0 to {GRID_SIZE-1}): "))
WIND_EAST = float(input("Enter Eastward wind probability (0.1 to 0.9): "))
BUDGET = int(input("Enter max firebreak cells allowed (e.g., 8): "))
GENERATIONS = int(input("Enter number of evolution generations (e.g., 15): "))

# States: 0 = Unburned, 1 = Burning, 2 = Burned, 3 = Firebreak
def evaluate_fitness(firebreak_coords):
    """Simulates fire spread and returns fitness (higher = less burned area)."""
    grid = [[0 for _ in range(GRID_SIZE)] for _ in range(GRID_SIZE)]

    # Place firebreaks
    for (fx, fy) in firebreak_coords:
        if (fx, fy) != (IGNITE_X, IGNITE_Y):
            grid[fx][fy] = 3

    # Start fire
    grid[IGNITE_X][IGNITE_Y] = 1
    burning = True

    while burning:
        burning = False
        next_grid = [row[:] for row in grid]
        for x in range(GRID_SIZE):
            for y in range(GRID_SIZE):
                if grid[x][y] == 1:
                    next_grid[x][y] = 2  # Becomes burned out
                    # Spread to neighbors (North, South, East, West)
                    neighbors = [(-1, 0, 0.3), (1, 0, 0.3), (0, 1, WIND_EAST), (0, -1, 0.1)]
                    for dx, dy, prob in neighbors:
                        nx, ny = x + dx, y + dy
                        if 0 <= nx < GRID_SIZE and 0 <= ny < GRID_SIZE:
                            if grid[nx][ny] == 0 and random.random() < prob:
                                next_grid[nx][ny] = 1
                                burning = True
        grid = next_grid

    # Count burned cells (State 2)
    burned_count = sum(row.count(2) for row in grid)

    # Fitness formula: maximize unburned land
    fitness = 1.0 / (1.0 + burned_count)
    return fitness

def generate_random_plan():
    all_coords = [(x, y) for x in range(GRID_SIZE) for y in range(GRID_SIZE) if (x, y) != (IGNITE_X, IGNITE_Y)]
    return random.sample(all_coords, min(BUDGET, len(all_coords)))

def mutate(plan):
    new_plan = list(plan)
    if new_plan and random.random() < 0.5:
        idx = random.randrange(len(new_plan))
        new_x, new_y = random.randrange(GRID_SIZE), random.randrange(GRID_SIZE)
        if (new_x, new_y) != (IGNITE_X, IGNITE_Y) and (new_x, new_y) not in new_plan:
            new_plan[idx] = (new_x, new_y)
    return new_plan

if __name__ == "__main__":
    # 2. Initialize Cellular Population Grid (4x4 parallel cells)
    POP_DIM = 4
    population = [[generate_random_plan() for _ in range(POP_DIM)] for _ in range(POP_DIM)]

    # 3. Parallel Evolution Loop
    with ProcessPoolExecutor() as executor:
        for gen in range(GENERATIONS):
            # Flatten grid to evaluate fitness in parallel across CPU cores
            flat_pop = [population[i][j] for i in range(POP_DIM) for j in range(POP_DIM)]
            flat_fitness = list(executor.map(evaluate_fitness, flat_pop))
            fitness_grid = [flat_fitness[i*POP_DIM:(i+1)*POP_DIM] for i in range(POP_DIM)]

            # Cellular Neighbor Selection & Update
            new_population = [[None for _ in range(POP_DIM)] for _ in range(POP_DIM)]
            for i in range(POP_DIM):
                for j in range(POP_DIM):
                    # Find best neighbor (Von Neumann neighborhood)
                    neighbors = [((i-1)%POP_DIM, j), ((i+1)%POP_DIM, j), (i, (j-1)%POP_DIM), (i, (j+1)%POP_DIM)]
                    best_ni, best_nj = max(neighbors, key=lambda pos: fitness_grid[pos[0]][pos[1]])

                    # Crossover & Mutation with best neighbor
                    parent1 = population[i][j]
                    parent2 = population[best_ni][best_nj]
                    half = BUDGET // 2
                    child = list(set(parent1[:half] + parent2[half:]))
                    while len(child) < BUDGET:
                        rx, ry = random.randrange(GRID_SIZE), random.randrange(GRID_SIZE)
                        if (rx, ry) != (IGNITE_X, IGNITE_Y) and (rx, ry) not in child:
                            child.append((rx, ry))
                    child = mutate(child)
                    new_population[i][j] = child

            population = new_population

    # 4. Output Best Solution Found
    best_plan = max(
        (population[i][j] for i in range(POP_DIM) for j in range(POP_DIM)),
        key=evaluate_fitness
    )
    print(f"\nOptimal Firebreak Coordinates: {best_plan}")
    print(f"Best Fitness Score: {evaluate_fitness(best_plan):.4f}")