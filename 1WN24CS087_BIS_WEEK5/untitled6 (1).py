import numpy as np
from scipy.spatial.distance import cdist


def ant_colony_optimization_tsp(
    waypoints, num_ants=10, generations=20, alpha=1.0, beta=2.0, evaporation=0.5
):
  """Finds the optimal drone path using the Ant Colony Optimization algorithm."""
  num_nodes = len(waypoints)
  dist_matrix = cdist(waypoints, waypoints, "euclidean")

  # Initialize pheromone matrix with small values
  pheromones = np.ones((num_nodes, num_nodes))
  best_path = None
  best_distance = float("inf")

  for gen in range(generations):
    all_paths = []
    all_distances = []

    for ant in range(num_ants):
      # Start each ant at node 0 (the launch station)
      current_node = 0
      visited = [current_node]
      path_distance = 0.0

      while len(visited) < num_nodes:
        # Calculate transition probabilities for unvisited nodes
        probabilities = []
        unvisited = [n for n in range(num_nodes) if n not in visited]

        for next_node in unvisited:
          # Pheromone factor (alpha) and distance heuristic visibility factor (beta)
          tau = pheromones[current_node][next_node] ** alpha
          eta = (1.0 / (dist_matrix[current_node][next_node] + 1e-9)) ** beta
          probabilities.append(tau * eta)

        probabilities = np.array(probabilities)
        probabilities /= probabilities.sum()

        # Select next node based on probability distribution
        chosen_node = np.random.choice(unvisited, p=probabilities)
        path_distance += dist_matrix[current_node][chosen_node]
        visited.append(chosen_node)
        current_node = chosen_node

      all_paths.append(visited)
      all_distances.append(path_distance)

      # Track the global best path
      if path_distance < best_distance:
        best_distance = path_distance
        best_path = visited

    # Evaporate pheromones
    pheromones *= 1.0 - evaporation

    # Deposit new pheromones based on the quality of routes found in this generation
    for path, dist in zip(all_paths, all_distances):
      for i in range(num_nodes - 1):
        pheromones[path[i]][path[i + 1]] += 1.0 / dist

  optimal_path_coords = waypoints[best_path]

  return {
      "optimal_path_waypoints": np.round(optimal_path_coords, 1),
      "optimality_score_meters": round(float(best_distance), 2),
      "total_waypoints": num_nodes,
  }


# --- Small Scale Inputs ---
FIELD_W = 30  # 30 meters wide
FIELD_H = 20  # 20 meters high
SWATH = 10  # 10 meters drone coverage width

# 1. Generate small set of 6 grid centers
x = np.arange(SWATH / 2, FIELD_W, SWATH)
y = np.arange(SWATH / 2, FIELD_H, SWATH)
X, Y = np.meshgrid(x, y)
field_grid = np.vstack([X.ravel(), Y.ravel()]).T

# 2. Run ACO Optimization
results = ant_colony_optimization_tsp(field_grid, num_ants=5, generations=15)

# --- Concise Output ---
print("--- ACO DRONE PATH OPTIMIZATION RESULTS ---")
print(f"Total Waypoints Generated: {results['total_waypoints']}")
print(f"Optimality Metric (Minimum Distance): {results['optimality_score_meters']} meters")
print("\nOptimal Path Coordinates (X, Y):")
print(results["optimal_path_waypoints"])