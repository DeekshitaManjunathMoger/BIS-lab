import random

# --- 1. Take Inputs from the User ---
print("--- GEP Flood Forecasting Symbolic Regression ---")
num_samples = int(input("Enter number of historical data points (e.g., 4): "))

dataset = []
print("Enter data as: Rainfall Soil_Moisture Observed_Runoff (space-separated)")
for i in range(num_samples):
    r, m, q = map(float, input(f"Sample {i+1}: ").split())
    dataset.append((r, m, q))

POP_SIZE = int(input("Enter population size (e.g., 50): "))
HEAD_LEN = int(input("Enter gene head length (e.g., 4): "))
GENERATIONS = int(input("Enter number of generations (e.g., 100): "))

# --- 2. GEP Configuration ---
FUNCTIONS = ['+', '-', '*', '/']
TERMINALS = ['R', 'M']
TAIL_LEN = HEAD_LEN * (2 - 1) + 1  # n_max = 2 for binary operators
GENE_LEN = HEAD_LEN + TAIL_LEN

def create_chromosome():
    head = [random.choice(FUNCTIONS + TERMINALS) for _ in range(HEAD_LEN)]
    tail = [random.choice(TERMINALS) for _ in range(TAIL_LEN)]
    return head + tail

# --- 3. Expression Tree Decoding & Evaluation ---
class Node:
    def __init__(self, val):
        self.val = val
        self.left = None
        self.right = None

def decode_to_tree(chromosome):
    """Translates a linear GEP chromosome into a branching Expression Tree."""
    root = Node(chromosome[0])
    queue = [root]
    idx = 1
    while queue and idx < len(chromosome):
        current = queue.pop(0)
        if current.val in FUNCTIONS:
            current.left = Node(chromosome[idx])
            queue.append(current.left)
            idx += 1
            if idx < len(chromosome):
                current.right = Node(chromosome[idx])
                queue.append(current.right)
                idx += 1
    return root

def evaluate_tree(node, r_val, m_val):
    if node.val == 'R':
        return r_val
    if node.val == 'M':
        return m_val

    left_val = evaluate_tree(node.left, r_val, m_val)
    right_val = evaluate_tree(node.right, r_val, m_val)

    if node.val == '+': return left_val + right_val
    if node.val == '-': return left_val - right_val
    if node.val == '*': return left_val * right_val
    if node.val == '/': return left_val / right_val if abs(right_val) > 1e-6 else 1.0

def tree_to_formula(node):
    if node.val in TERMINALS:
        return node.val
    return f"({tree_to_formula(node.left)} {node.val} {tree_to_formula(node.right)})"

def calculate_fitness(chromosome):
    """Calculates fitness based on Mean Squared Error against user dataset."""
    tree = decode_to_tree(chromosome)
    total_sq_error = 0.0
    for r, m, q_actual in dataset:
        try:
            q_pred = evaluate_tree(tree, r, m)
            total_sq_error += (q_actual - q_pred) ** 2
        except OverflowError:
            return 0.0
    mse = total_sq_error / len(dataset)
    return 1000.0 / (1.0 + mse)

# --- 4. Genetic Operators ---
def mutate(chrom):
    mutant = chrom[:]
    idx = random.randrange(GENE_LEN)
    if idx < HEAD_LEN:
        mutant[idx] = random.choice(FUNCTIONS + TERMINALS)
    else:
        mutant[idx] = random.choice(TERMINALS)
    return mutant

def crossover(p1, p2):
    pt = random.randint(1, GENE_LEN - 1)
    return p1[:pt] + p2[pt:], p2[:pt] + p1[pt:]

# --- 5. Main Evolution Loop ---
if __name__ == "__main__":
    population = [create_chromosome() for _ in range(POP_SIZE)]

    for gen in range(GENERATIONS):
        scored_pop = [(calculate_fitness(c), c) for c in population]
        scored_pop.sort(key=lambda x: x[0], reverse=True)

        # Elitism: keep top 2 chromosomes
        next_gen = [scored_pop[0][1], scored_pop[1][1]]

        while len(next_gen) < POP_SIZE:
            # Tournament selection from top 50%
            p1 = random.choice(scored_pop[:POP_SIZE // 2])[1]
            p2 = random.choice(scored_pop[:POP_SIZE // 2])[1]

            c1, c2 = crossover(p1, p2) if random.random() < 0.7 else (p1[:], p2[:])
            if random.random() < 0.3: c1 = mutate(c1)
            if random.random() < 0.3: c2 = mutate(c2)

            next_gen.extend([c1, c2])

        population = next_gen[:POP_SIZE]

    best_fitness, best_chrom = max(((calculate_fitness(c), c) for c in population), key=lambda x: x[0])
    best_tree = decode_to_tree(best_chrom)

    print("\n--- Optimization Results ---")
    print(f"Best Linear Chromosome : {best_chrom}")
    print(f"Discovered Equation    : Q = {tree_to_formula(best_tree)}")
    print(f"Best Fitness Score     : {best_fitness:.4f} (Max = 1000)")