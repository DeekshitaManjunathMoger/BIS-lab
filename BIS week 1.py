import random


# ============================================================
# 1. INPUT DATA
# ============================================================

# Each class = (subject, faculty, student_group)

classes = [
    ("Mathematics", "Dr. Smith", "G1"),
    ("Physics", "Dr. John", "G1"),
    ("Programming", "Dr. Smith", "G2"),
    ("English", "Dr. Mary", "G2"),
    ("Database", "Dr. John", "G3"),
    ("Networks", "Dr. Mary", "G3"),
    ("AI", "Dr. Smith", "G4"),
    ("Operating Systems", "Dr. John", "G4")
]

# Available time slots
slots = [
    "Monday 9-11",
    "Monday 11-1",
    "Tuesday 9-11",
    "Tuesday 11-1",
    "Wednesday 9-11",
    "Wednesday 11-1"
]

# Available rooms
rooms = [
    "Room 101",
    "Room 102",
    "Room 103"
]


# ============================================================
# 2. GENETIC ALGORITHM PARAMETERS
# ============================================================

POPULATION_SIZE = 100
GENERATIONS = 1000

MUTATION_RATE = 0.10

TOURNAMENT_SIZE = 3

# If we reach zero conflicts, we can stop.
TARGET_CONFLICTS = 0


# ============================================================
# 3. CREATE A RANDOM CHROMOSOME
# ============================================================

def create_chromosome():
    """
    Create one random timetable.

    Each gene is:
        (slot_index, room_index)

    One gene corresponds to one class.
    """

    chromosome = []

    for _ in classes:

        slot = random.randrange(len(slots))
        room = random.randrange(len(rooms))

        chromosome.append((slot, room))

    return chromosome


# ============================================================
# 4. CREATE INITIAL POPULATION
# ============================================================

def create_population():
    population = []

    for _ in range(POPULATION_SIZE):
        chromosome = create_chromosome()
        population.append(chromosome)

    return population


# ============================================================
# 5. FITNESS FUNCTION
# ============================================================

def calculate_conflicts(chromosome):
    """
    Count the number of scheduling conflicts.

    Conflicts occur when two classes have the same time slot
    and share:

        1. Same faculty
        2. Same room
        3. Same student group
    """

    conflicts = 0

    # Compare every pair of classes
    for i in range(len(classes)):

        for j in range(i + 1, len(classes)):

            subject1, faculty1, group1 = classes[i]
            subject2, faculty2, group2 = classes[j]

            slot1, room1 = chromosome[i]
            slot2, room2 = chromosome[j]

            # Conflicts matter only if classes occur
            # at the same time.
            if slot1 == slot2:

                # Faculty conflict
                if faculty1 == faculty2:
                    conflicts += 1

                # Room conflict
                if room1 == room2:
                    conflicts += 1

                # Student group conflict
                if group1 == group2:
                    conflicts += 1

    return conflicts


def fitness(chromosome):
    """
    Fitness = 1 / (1 + number_of_conflicts)

    Fewer conflicts => higher fitness.

    If conflicts = 0:
        fitness = 1

    If conflicts = 1:
        fitness = 0.5

    If conflicts = 2:
        fitness = 0.333
    """

    conflicts = calculate_conflicts(chromosome)

    return 1 / (1 + conflicts)


# ============================================================
# 6. SELECTION
# ============================================================

def tournament_selection(population):
    """
    Select one chromosome using tournament selection.

    Randomly select a few chromosomes and return
    the one having the highest fitness.
    """

    tournament = random.sample(
        population,
        TOURNAMENT_SIZE
    )

    winner = max(
        tournament,
        key=fitness
    )

    return winner.copy()


# ============================================================
# 7. SINGLE-POINT CROSSOVER
# ============================================================

def single_point_crossover(parent1, parent2):
    """
    Perform single-point crossover.

    Example:

    Parent 1:
    A B C | D E F

    Parent 2:
    X Y Z | P Q R

    Child 1:
    A B C | P Q R

    Child 2:
    X Y Z | D E F
    """

    # Random crossover position
    point = random.randint(1, len(parent1) - 1)

    child1 = (
        parent1[:point] +
        parent2[point:]
    )

    child2 = (
        parent2[:point] +
        parent1[point:]
    )

    return child1, child2


# ============================================================
# 8. MUTATION
# ============================================================

def mutation(chromosome):
    """
    Mutation randomly changes the slot or room of a class.

    According to the problem:
        mutation reassigns a random slot or room.
    """

    mutated = chromosome.copy()

    for i in range(len(mutated)):

        # Decide whether this gene should mutate
        if random.random() < MUTATION_RATE:

            slot, room = mutated[i]

            # Randomly choose whether to change
            # slot or room.

            if random.random() < 0.5:

                # Change time slot
                slot = random.randrange(len(slots))

            else:

                # Change room
                room = random.randrange(len(rooms))

            mutated[i] = (slot, room)

    return mutated


# ============================================================
# 9. GET BEST CHROMOSOME
# ============================================================

def get_best(population):

    return max(
        population,
        key=fitness
    )


# ============================================================
# 10. GENETIC ALGORITHM
# ============================================================

def genetic_algorithm():

    # Create initial population
    population = create_population()

    best_solution = None
    best_fitness = -1

    for generation in range(GENERATIONS):

        new_population = []

        # Keep the best chromosome (elitism)
        current_best = get_best(population)

        current_fitness = fitness(current_best)

        if current_fitness > best_fitness:

            best_solution = current_best.copy()
            best_fitness = current_fitness

        # Check whether a conflict-free timetable exists
        if calculate_conflicts(current_best) == TARGET_CONFLICTS:

            print(
                f"Solution found at generation "
                f"{generation}"
            )

            return current_best

        # Elitism
        new_population.append(current_best.copy())

        # Create new generation
        while len(new_population) < POPULATION_SIZE:

            # Selection
            parent1 = tournament_selection(population)
            parent2 = tournament_selection(population)

            # Crossover
            child1, child2 = single_point_crossover(
                parent1,
                parent2
            )

            # Mutation
            child1 = mutation(child1)
            child2 = mutation(child2)

            # Add children
            new_population.append(child1)

            if len(new_population) < POPULATION_SIZE:
                new_population.append(child2)

        population = new_population

        # Display progress
        if generation % 50 == 0:

            conflicts = calculate_conflicts(current_best)

            print(
                f"Generation: {generation}, "
                f"Conflicts: {conflicts}, "
                f"Fitness: {current_fitness:.4f}"
            )

    return best_solution


