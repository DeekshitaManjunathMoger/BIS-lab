def calculate_conflicts(
    chromosome,
    classes
):

    conflicts = 0


    for i in range(len(classes)):

        for j in range(i + 1, len(classes)):

            subject1, faculty1, group1 = classes[i]
            subject2, faculty2, group2 = classes[j]

            slot1, room1 = chromosome[i]
            slot2, room2 = chromosome[j]


            if slot1 == slot2:

                if faculty1 == faculty2:

                    conflicts += 1

                if room1 == room2:

                    conflicts += 1

                if group1 == group2:

                    conflicts += 1

    return conflicts

def fitness(
    chromosome,
    classes
):

    conflicts = calculate_conflicts(
        chromosome,
        classes
    )


    return 1 / (1 + conflicts)

def tournament_selection(
    population,
    classes,
    tournament_size
):


    tournament = random.sample(
        population,
        tournament_size
    )


    winner = max(
        tournament,
        key=lambda chromosome:
        fitness(chromosome, classes)
    )

    return winner.copy()


def single_point_crossover(
    parent1,
    parent2
):


    point = random.randint(
        1,
        len(parent1) - 1
    )

    child1 = (
        parent1[:point] +
        parent2[point:]
    )

    child2 = (
        parent2[:point] +
        parent1[point:]
    )

    return child1, child2

def mutation(
    chromosome,
    slots,
    rooms,
    mutation_rate
):

    mutated = chromosome.copy()

    for i in range(len(mutated)):


        if random.random() < mutation_rate:

            slot, room = mutated[i]



            if random.random() < 0.5:


                slot = random.randrange(
                    len(slots)
                )

            else:


                room = random.randrange(
                    len(rooms)
                )

            mutated[i] = (
                slot,
                room
            )

    return mutated


def get_best(
    population,
    classes
):

    return max(
        population,
        key=lambda chromosome:
        fitness(chromosome, classes)
    )

def genetic_algorithm(
    classes,
    slots,
    rooms,
    population_size,
    generations,
    mutation_rate,
    tournament_size
):

    population = create_population(
        classes,
        slots,
        rooms,
        population_size
    )

    best_solution = None
    best_fitness = -1

    for generation in range(generations):


        current_best = get_best(
            population,
            classes
        )

        current_fitness = fitness(
            current_best,
            classes
        )

        current_conflicts = calculate_conflicts(
            current_best,
            classes
        )

        if current_fitness > best_fitness:

            best_solution = current_best.copy()

            best_fitness = current_fitness

        if current_conflicts == 0:

            print(
                f"\nSolution found at generation "
                f"{generation + 1}!"
            )

            return current_best

        new_population = []

        new_population.append(
            current_best.copy()
        )

        while len(new_population) < population_size:

            parent1 = tournament_selection(
                population,
                classes,
                tournament_size
            )

            parent2 = tournament_selection(
                population,
                classes,
                tournament_size
            )


            child1, child2 = single_point_crossover(
                parent1,
                parent2
            )

            child1 = mutation(
                child1,
                slots,
                rooms,
                mutation_rate
            )

            child2 = mutation(
                child2,
                slots,
                rooms,
                mutation_rate
            )

            new_population.append(child1)

            if len(new_population) < population_size:

                new_population.append(child2)

        population = new_population


        if (
            generation % 50 == 0
            or generation == generations - 1
        ):

            print(
                f"Generation {generation + 1:4d} | "
                f"Conflicts: {current_conflicts:3d} | "
                f"Fitness: {current_fitness:.4f}"
            )

    return best_solution


