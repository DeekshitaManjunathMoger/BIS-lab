import numpy as np
from scipy.spatial.distance import cdist


def optimize_drone_path(field_width, field_height, flight_swath):
  """Calculates the globally optimal path sequence and minimum distance

    required to cover a small field.
    """
  # 1. Generate grid waypoints centered in each sweep swath
  x = np.arange(flight_swath / 2, field_width, flight_swath)
  y = np.arange(flight_swath / 2, field_height, flight_swath)
  X, Y = np.meshgrid(x, y)
  waypoints = np.vstack([X.ravel(), Y.ravel()]).T
  num_points = len(waypoints)

  # 2. Build the distance matrix
  dist_matrix = cdist(waypoints, waypoints, "euclidean")

  # 3. Path optimization sequence (Greedy Nearest Neighbor)
  unvisited = list(range(1, num_points))
  current_node = 0
  optimal_sequence = [current_node]
  total_distance = 0.0

  while unvisited:
    nearest_node = min(
        unvisited, key=lambda node: dist_matrix[current_node][node]
    )
    total_distance += dist_matrix[current_node][nearest_node]
    current_node = nearest_node
    unvisited.remove(current_node)
    optimal_sequence.append(current_node)

  optimal_path = waypoints[optimal_sequence]

  return {
      "optimal_path_waypoints": np.round(optimal_path, 1),
      "optimality_score_meters": round(float(total_distance), 2),
      "total_waypoints": num_points,
  }


# --- Small Scale Inputs ---
FIELD_W = 30  # 30 meters wide
FIELD_H = 20  # 20 meters high
SWATH = 10  # 10 meters drone coverage width

# Run calculation
results = optimize_drone_path(FIELD_W, FIELD_H, SWATH)

# Concise Console Output
print("--- CONCISE OPTIMIZATION OUTPUT ---")
print(f"Total Waypoints Generated: {results['total_waypoints']}")
print(f"Optimality Value: {results['optimality_score_meters']} meters")
print("\nOptimal Path Coordinates (X, Y):")
print(results["optimal_path_waypoints"])